#!/usr/bin/env bash
# ZYLORACLOUD Pterodactyl Panel + Wings installer
# Target: Ubuntu 24.04 LTS (fresh VPS recommended)
# Run as root: bash zyloracloud-install.sh
#
# This script installs dependencies, MariaDB, Redis, Nginx, PHP 8.3,
# Docker and the official Pterodactyl Panel files. It creates the panel
# database and guides the operator through panel configuration, SSL,
# and Wings node configuration.
#
# Important:
# - Panel and Wings can run on one VPS for small deployments, but a
#   separate node VPS is recommended for production.
# - A real DNS A/AAAA record must point the panel domain to this VPS.
# - Cloudflare proxy must be DNS-only during HTTP-01 certificate issuance.
# - Wings requires a node configuration generated by the Panel UI.
# - Review commands before accepting; this is not a substitute for backups.

set -Eeuo pipefail
IFS=$'\n\t'

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
log(){ echo -e "${GREEN}[ZYLORACLOUD]${NC} $*"; }
warn(){ echo -e "${YELLOW}[WARNING]${NC} $*" >&2; }
die(){ echo -e "${RED}[ERROR]${NC} $*" >&2; exit 1; }
trap 'die "Installer stopped at line $LINENO. Review the error above; no automatic rollback was attempted."' ERR

[[ $EUID -eq 0 ]] || die "Run as root: sudo bash $0"
[[ -r /etc/os-release ]] || die "Cannot identify operating system."
. /etc/os-release
[[ "${ID:-}" == "ubuntu" && "${VERSION_ID:-}" == "24.04" ]] || die "This installer supports Ubuntu 24.04 LTS only. Detected: ${PRETTY_NAME:-unknown}"

if [[ -e /var/www/pterodactyl/.env ]]; then
  die "An existing Pterodactyl Panel installation was detected at /var/www/pterodactyl. Refusing to overwrite it."
fi

clear || true
echo -e "${BLUE}"
cat <<'BANNER'
 ____        _                   ____ _                 _
|_  /  _   _| | ___  _ __ __ _ / ___| | ___  _   _  __| |
 / /  | | | | |/ _ \| '__/ _` | |   | |/ _ \| | | |/ _` |
/___| | |_| | | (_) | | | (_| | |___| | (_) | |_| | (_| |
       \__,_|_|\___/|_|  \__,_|\____|_|\___/ \__,_|\__,_|
       PTERODACTYL PANEL + WINGS INSTALLER
BANNER
echo -e "${NC}"

warn "Use on a fresh Ubuntu 24.04 VPS. This changes firewall, packages, services and Nginx."
warn "Take a VPS snapshot first. Do not run on a machine hosting important existing services."
read -r -p "Type INSTALL to continue: " CONFIRM
[[ "$CONFIRM" == "INSTALL" ]] || die "Cancelled."

read -r -p "Panel domain (example: panel.example.com): " PANEL_DOMAIN
PANEL_DOMAIN="${PANEL_DOMAIN,,}"
[[ "$PANEL_DOMAIN" =~ ^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$ ]] || die "Invalid domain."
read -r -p "Let's Encrypt email address: " LE_EMAIL
[[ "$LE_EMAIL" =~ ^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$ ]] || die "Invalid email address."

PUBLIC_IP="$(curl -4fsS --max-time 10 https://api.ipify.org || true)"
echo
log "Detected public IPv4: ${PUBLIC_IP:-not detected}"
echo "Before continuing, make sure:"
echo "  1) ${PANEL_DOMAIN} has an A record pointing to this VPS."
echo "  2) If using Cloudflare, set the record to DNS-only (grey cloud) temporarily."
echo "  3) Ports 80 and 443 are reachable from the internet."
read -r -p "DNS and ports are ready? Type YES: " DNS_OK
[[ "$DNS_OK" == "YES" ]] || die "Configure DNS/firewall first, then rerun."

export DEBIAN_FRONTEND=noninteractive
log "Updating Ubuntu packages..."
apt-get update
apt-get -y upgrade
apt-get install -y ca-certificates curl gnupg apt-transport-https software-properties-common \
  lsb-release unzip tar git cron mariadb-server redis-server nginx certbot python3-certbot-nginx \
  php8.3 php8.3-cli php8.3-common php8.3-gd php8.3-mysql php8.3-mbstring php8.3-bcmath \
  php8.3-xml php8.3-curl php8.3-zip php8.3-fpm php8.3-intl php8.3-readline

log "Installing Composer..."
EXPECTED_CHECKSUM="$(curl -fsSL https://composer.github.io/installer.sig)"
php -r "copy('https://getcomposer.org/installer', 'composer-setup.php');"
ACTUAL_CHECKSUM="$(php -r "echo hash_file('sha384', 'composer-setup.php');")"
[[ "$EXPECTED_CHECKSUM" == "$ACTUAL_CHECKSUM" ]] || { rm -f composer-setup.php; die "Composer installer checksum verification failed."; }
php composer-setup.php --install-dir=/usr/local/bin --filename=composer
rm -f composer-setup.php

log "Installing Docker Engine from Docker's official Ubuntu repository..."
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc
. /etc/os-release
cat > /etc/apt/sources.list.d/docker.sources <<EOF
Types: deb
URIs: https://download.docker.com/linux/ubuntu
Suites: ${UBUNTU_CODENAME}
Components: stable
Architectures: $(dpkg --print-architecture)
Signed-By: /etc/apt/keyrings/docker.asc
EOF
apt-get update
apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin

log "Enabling required services..."
systemctl enable --now mariadb redis-server nginx php8.3-fpm docker

log "Creating Pterodactyl database and restricted database user..."
DB_NAME="panel"
DB_USER="pterodactyl"
DB_PASS="$(openssl rand -hex 24)"
mysql <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\`;
CREATE USER IF NOT EXISTS '${DB_USER}'@'127.0.0.1' IDENTIFIED BY '${DB_PASS}';
ALTER USER '${DB_USER}'@'127.0.0.1' IDENTIFIED BY '${DB_PASS}';
GRANT ALL PRIVILEGES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'127.0.0.1';
FLUSH PRIVILEGES;
SQL

log "Downloading the official Pterodactyl Panel release archive..."
install -d -m 0755 /var/www/pterodactyl
cd /var/www/pterodactyl
curl -fL --retry 3 https://github.com/pterodactyl/panel/releases/latest/download/panel.tar.gz -o panel.tar.gz
tar -xzf panel.tar.gz
rm -f panel.tar.gz
chmod -R 755 storage/* bootstrap/cache/
cp .env.example .env
COMPOSER_ALLOW_SUPERUSER=1 composer install --no-dev --optimize-autoloader --no-interaction

log "Preparing application environment..."
php artisan key:generate --force
warn "The next setup prompts are interactive. Use https://${PANEL_DOMAIN}, choose Redis for cache/session/queue, and use the database credentials shown below."
echo "Database: ${DB_NAME} | User: ${DB_USER} | Password: ${DB_PASS}"
php artisan p:environment:setup
php artisan p:environment:database
php artisan p:environment:mail
php artisan migrate --seed --force

log "Creating first Panel administrator..."
php artisan p:user:make

log "Setting file ownership..."
chown -R www-data:www-data /var/www/pterodactyl

log "Writing Nginx virtual host..."
cat > /etc/nginx/sites-available/pterodactyl.conf <<EOF
server {
    listen 80;
    listen [::]:80;
    server_name ${PANEL_DOMAIN};
    root /var/www/pterodactyl/public;
    index index.php;
    charset utf-8;
    client_max_body_size 100m;
    location / { try_files \$uri \$uri/ /index.php?\$query_string; }
    location = /favicon.ico { access_log off; log_not_found off; }
    location = /robots.txt { access_log off; log_not_found off; }
    access_log off;
    error_log /var/log/nginx/pterodactyl.app-error.log error;
    location ~ \.php$ {
        fastcgi_split_path_info ^(.+\.php)(/.+)$;
        fastcgi_pass unix:/run/php/php8.3-fpm.sock;
        fastcgi_index index.php;
        include fastcgi_params;
        fastcgi_param PHP_VALUE "upload_max_filesize=100M \n post_max_size=100M";
        fastcgi_param SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        fastcgi_param HTTP_PROXY "";
        fastcgi_intercept_errors off;
        fastcgi_buffer_size 16k;
        fastcgi_buffers 4 16k;
        fastcgi_connect_timeout 300;
        fastcgi_send_timeout 300;
        fastcgi_read_timeout 300;
    }
    location ~ /\. { deny all; }
}
EOF
ln -sfn /etc/nginx/sites-available/pterodactyl.conf /etc/nginx/sites-enabled/pterodactyl.conf
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl reload nginx

log "Requesting Let's Encrypt certificate..."
certbot --nginx --non-interactive --agree-tos --email "${LE_EMAIL}" -d "${PANEL_DOMAIN}" --redirect

log "Installing Panel scheduled tasks and queue worker..."
(crontab -u www-data -l 2>/dev/null | grep -v 'artisan schedule:run' || true; \
 echo '* * * * * php /var/www/pterodactyl/artisan schedule:run >> /dev/null 2>&1') | crontab -u www-data -
cat > /etc/systemd/system/pteroq.service <<'EOF'
[Unit]
Description=Pterodactyl Queue Worker
After=redis-server.service
[Service]
User=www-data
Group=www-data
Restart=always
ExecStart=/usr/bin/php /var/www/pterodactyl/artisan queue:work --queue=high,standard,low --sleep=3 --tries=3
[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable --now pteroq

log "Configuring firewall if UFW is installed..."
if command -v ufw >/dev/null 2>&1; then
  ufw allow OpenSSH
  ufw allow 80/tcp
  ufw allow 443/tcp
  ufw allow 8080/tcp
  ufw allow 2022/tcp
  warn "UFW was not enabled automatically to avoid locking you out of SSH. Review: ufw status"
fi

log "Installing Wings binary..."
install -d -m 0755 /etc/pterodactyl
ARCH="$(uname -m)"
case "$ARCH" in
  x86_64) WINGS_ARCH="amd64" ;;
  aarch64|arm64) WINGS_ARCH="arm64" ;;
  *) die "Unsupported CPU architecture: $ARCH" ;;
esac
curl -fL --retry 3 "https://github.com/pterodactyl/wings/releases/latest/download/wings_linux_${WINGS_ARCH}" -o /usr/local/bin/wings
chmod 0755 /usr/local/bin/wings
cat > /etc/systemd/system/wings.service <<'EOF'
[Unit]
Description=Pterodactyl Wings Daemon
After=docker.service
Requires=docker.service
[Service]
User=root
WorkingDirectory=/etc/pterodactyl
LimitNOFILE=4096
PIDFile=/var/run/wings/daemon.pid
ExecStart=/usr/local/bin/wings
Restart=on-failure
StartLimitInterval=180
StartLimitBurst=30
[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable wings

cat > /root/zyloracloud-install-info.txt <<EOF
ZYLORACLOUD Pterodactyl installation information
Panel URL: https://${PANEL_DOMAIN}
Database: ${DB_NAME}
Database user: ${DB_USER}
Database password: ${DB_PASS}
Wings binary: /usr/local/bin/wings
Wings config path: /etc/pterodactyl/config.yml
EOF
chmod 600 /root/zyloracloud-install-info.txt

echo
echo -e "${GREEN}PANEL FILES + WINGS BINARY INSTALLED${NC}"
echo "Panel URL: https://${PANEL_DOMAIN}"
echo "Database credentials saved securely in: /root/zyloracloud-install-info.txt"
echo
warn "FINAL REQUIRED STEPS — do not start Wings until its node config exists:"
echo "1) Sign in to the Panel and open Admin -> Locations, then create a location."
echo "2) Admin -> Nodes -> Create Node. Use this VPS public IP."
echo "3) Set FQDN to a node DNS name (not necessarily the panel domain), scheme HTTPS only if node TLS is configured."
echo "4) In the Node Configuration tab, copy the generated configuration."
echo "5) On this VPS run: cd /etc/pterodactyl && wings configure --panel-url https://${PANEL_DOMAIN} --token YOUR_NODE_CONFIG_TOKEN --node YOUR_NODE_ID"
echo "   Use the token and node ID from the Panel's Node Configuration page; do not share the token."
echo "6) Then run: systemctl start wings"
echo "7) Check: systemctl status wings --no-pager; journalctl -u wings -n 80 --no-pager"
echo
warn "Do not expose Wings port 8080 without TLS on an untrusted public network. Configure node TLS or use a trusted private network/reverse proxy."
warn "For production, use a separate node VPS and configure its DNS, TLS, firewall and allocation ports independently."
